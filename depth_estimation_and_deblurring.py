# -------- SIFT-Based Alignment --------
def align_images_sift(img1, img2):
    """
    Aligns img1 to img2 using SIFT and homography transformation.
    """
    gray1 = cv2.cvtColor(img1, cv2.COLOR_BGR2GRAY)
    gray2 = cv2.cvtColor(img2, cv2.COLOR_BGR2GRAY)

    sift = cv2.SIFT_create()
    kp1, des1 = sift.detectAndCompute(gray1, None)
    kp2, des2 = sift.detectAndCompute(gray2, None)

    # Use FLANN-based matcher
    index_params = dict(algorithm=1, trees=5)
    search_params = dict()
    flann = cv2.FlannBasedMatcher(index_params, search_params)
    matches = flann.knnMatch(des1, des2, k=2)

    # Lowe's ratio test
    good_matches = [m for m, n in matches if m.distance < 0.75 * n.distance]

    if len(good_matches) >= 10:
        src_pts = np.float32([kp1[m.queryIdx].pt for m in good_matches]).reshape(-1, 1, 2)
        dst_pts = np.float32([kp2[m.trainIdx].pt for m in good_matches]).reshape(-1, 1, 2)
        H, _ = cv2.findHomography(src_pts, dst_pts, cv2.RANSAC, 5.0)
        aligned = cv2.warpPerspective(img1, H, (img2.shape[1], img2.shape[0]))
        return aligned
    else:
        print("Not enough matches to align.")
        return img1  # fallback

# Align the near image to far image
aligned_near = align_images_sift(img_near, img_far)
gray_aligned_near = cv2.cvtColor(aligned_near, cv2.COLOR_BGR2GRAY)

# -------- Sharpness Estimation Function --------
def estimate_sharpness(img):
    """
    Estimates sharpness using the absolute Laplacian.
    """
    lap = cv2.Laplacian(img, cv2.CV_64F)
    return np.abs(lap)

# -------- Depth Map Estimation --------
def estimate_depth_map(gray_near, gray_far, guidance_img):
    """
    Estimates relative depth using sharpness difference and smooths it.
    """
    sharp_near = estimate_sharpness(gray_near)
    sharp_far = estimate_sharpness(gray_far)

    raw_depth = sharp_far - sharp_near

    depth_norm = cv2.normalize(raw_depth, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
    guided_depth = guidedFilter(guidance_img, depth_norm, radius=8, eps=500)
    return guided_depth

# Estimate depth map
depth_map = estimate_depth_map(gray_aligned_near, gray_far, gray_aligned_near)

# -------- All-in-Focus Image --------
def construct_all_in_focus_image(img_near, img_far):
    """
    Combines sharper regions from both images to make all-in-focus image.
    """
    gray_near = cv2.cvtColor(img_near, cv2.COLOR_BGR2GRAY)
    gray_far = cv2.cvtColor(img_far, cv2.COLOR_BGR2GRAY)

    sharp_near = estimate_sharpness(gray_near)
    sharp_far = estimate_sharpness(gray_far)

    mask = (sharp_near > sharp_far).astype(np.float32)
    mask = cv2.GaussianBlur(mask, (9, 9), 0)
    mask_3ch = np.repeat(mask[:, :, np.newaxis], 3, axis=2)

    fused = (img_near * mask_3ch + img_far * (1 - mask_3ch)).astype(np.uint8)
    return fused

# Create all-in-focus image
all_in_focus = construct_all_in_focus_image(aligned_near, img_far)

